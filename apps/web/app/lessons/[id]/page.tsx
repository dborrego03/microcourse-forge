import Link from "next/link";
import { notFound } from "next/navigation";
import { Suspense } from "react";

import { getLesson } from "../../lib/api";
import { Quiz } from "./quiz";

export default function LessonPage({ params }: PageProps<"/lessons/[id]">) {
  return (
    <Suspense fallback={<p className="text-stone-600">Loading lesson…</p>}>
      {params.then(({ id }) => (
        <LessonView id={id} />
      ))}
    </Suspense>
  );
}

async function LessonView({ id }: { id: string }) {
  const data = await getLesson(id);
  if (!data) notFound();
  if (data.status !== "ready" || !data.lesson || !data.quiz) {
    return (
      <p>
        This lesson is {data.status}.{" "}
        <Link href="/" className="underline">
          Back
        </Link>
      </p>
    );
  }

  const { lesson, quiz, sources } = data;
  // Number sources in the order they appear in the list at the bottom.
  const number = new Map(sources.map((s, i) => [s.id, i + 1]));
  const cite = (ids: number[]) =>
    [...ids]
      .sort((a, b) => (number.get(a) ?? 0) - (number.get(b) ?? 0))
      .map((id) => (
        <a key={id} href={`#source-${id}`} className="ml-0.5 align-super text-xs text-teal-800 underline">
          [{number.get(id)}]
        </a>
      ));
  const license = sources[0];

  return (
    <article className="space-y-8">
      <header>
        <p className="text-sm uppercase tracking-wide text-stone-600">{data.request.level} lesson</p>
        <h1 className="text-3xl font-semibold">{lesson.title}</h1>
      </header>

      <section aria-labelledby="objectives">
        <h2 id="objectives" className="mb-2 text-lg font-semibold">
          By the end you should be able to
        </h2>
        <ol className="list-decimal space-y-1 pl-6">
          {lesson.objectives.map((o) => (
            <li key={o}>{o}</li>
          ))}
        </ol>
      </section>

      {lesson.sections.map((s) => (
        <section key={s.heading}>
          <h2 className="mb-2 text-xl font-semibold">{s.heading}</h2>
          <p className="leading-relaxed">
            {s.body}
            {cite(s.sources)}
          </p>
          {s.example && (
            <p className="mt-3 border-l-4 border-teal-700 bg-white px-4 py-2">
              <span className="font-medium">Example: </span>
              {s.example}
            </p>
          )}
        </section>
      ))}

      <section>
        <h2 className="mb-2 text-xl font-semibold">Summary</h2>
        <p className="leading-relaxed">{lesson.summary}</p>
      </section>

      <Quiz questions={quiz.questions} sourceNumbers={Object.fromEntries(number)} />

      <section aria-labelledby="sources">
        <h2 id="sources" className="mb-2 text-xl font-semibold">
          Sources
        </h2>
        <ol className="space-y-3">
          {sources.map((s) => (
            <li key={s.id} id={`source-${s.id}`} className="rounded-md border border-stone-200 bg-white p-3">
              <details>
                <summary className="cursor-pointer">
                  [{number.get(s.id)}] {s.section}, PDF pages {s.pages}
                </summary>
                <p className="mt-2 text-sm leading-relaxed text-stone-700">{s.text}</p>
              </details>
            </li>
          ))}
        </ol>
        {license && (
          <p className="mt-4 text-sm text-stone-600">
            Adapted from{" "}
            <a href={license.source_url} className="underline">
              {license.title}
            </a>{" "}
            under{" "}
            <a href={license.license_url} className="underline">
              {license.license}
            </a>
            . {license.attribution}. This lesson is shared under the same license. Generated by {data.model} (
            {data.prompt_version}).
          </p>
        )}
      </section>
    </article>
  );
}
